"""Serve the real API on a disposable test schema, never on development data."""
import argparse
import json
import os
import secrets
import re
import sys
from pathlib import Path
from uuid import uuid4

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from alembic import command
from alembic.config import Config
from sqlalchemy import create_engine, event, text
from sqlalchemy.orm import Session
import uvicorn

from tests.db_safety import assert_test_database, test_database_url

STATE = ROOT / ".tools" / "e2e-state.json"


def cleanup(engine, schema):
    if not re.fullmatch(r"test_e2e_[0-9a-f]{32}", schema):
        raise RuntimeError("Refusing cleanup of a schema not generated by the E2E harness.")
    with engine.begin() as connection:
        assert_test_database(connection)
        connection.execute(text(f'DROP SCHEMA IF EXISTS "{schema}" CASCADE'))
    (ROOT / ".tools" / "e2e-credentials.json").unlink(missing_ok=True)
    STATE.unlink(missing_ok=True)


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--port", type=int, default=9001)
    parser.add_argument("--cleanup", action="store_true")
    args = parser.parse_args()
    os.environ["JWT_SECRET"] = secrets.token_urlsafe(48)
    from app.database import get_db
    from app.main import app
    from app.models.commerce import User
    from app.security import hasher

    engine = create_engine(test_database_url(ROOT / ".env.test"), hide_parameters=True,
                           connect_args={"connect_timeout": 5})
    if args.cleanup:
        if STATE.is_file():
            cleanup(engine, json.loads(STATE.read_text(encoding="utf-8"))["schema"])
        engine.dispose()
        return
    schema = "test_e2e_" + uuid4().hex
    created = False
    credentials_path = ROOT / ".tools" / "e2e-credentials.json"
    try:
        with engine.begin() as connection:
            assert_test_database(connection)
            connection.execute(text(f'CREATE SCHEMA "{schema}"'))
            connection.execute(text(f'SET LOCAL search_path TO "{schema}"'))
            config = Config(str(ROOT / "alembic.ini"))
            config.set_main_option("script_location", str(ROOT / "alembic"))
            config.attributes["connection"] = connection
            command.upgrade(config, "head")
        created = True
        STATE.parent.mkdir(exist_ok=True)
        STATE.write_text(json.dumps({"schema": schema}), encoding="utf-8")

        def get_test_db():
            with Session(engine) as session:
                @event.listens_for(session, "after_begin")
                def isolate(_session, _transaction, connection):
                    connection.execute(text(f'SET LOCAL search_path TO "{schema}"'))
                yield session

        password = secrets.token_urlsafe(24)
        credentials = {"email": "portfolio@example.com", "password": password}
        credentials_path.parent.mkdir(exist_ok=True)
        credentials_path.write_text(json.dumps(credentials), encoding="utf-8")
        session_generator = get_test_db()
        db = next(session_generator)
        try:
            db.add(User(email=credentials["email"], password_hash=hasher.hash(password), role="admin"))
            db.commit()
        finally:
            session_generator.close()
        app.dependency_overrides[get_db] = get_test_db
        print("E2E API uses a generated schema in orderflow_test_db; credentials hidden.", flush=True)
        uvicorn.run(app, host="127.0.0.1", port=args.port)
    finally:
        app.dependency_overrides.pop(get_db, None)
        if created:
            cleanup(engine, schema)
        credentials_path.unlink(missing_ok=True)
        engine.dispose()


if __name__ == "__main__":
    main()
